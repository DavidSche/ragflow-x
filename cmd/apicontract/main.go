func argType(an *analyzer, call *ast.CallExpr, i int) types.Type {
	if i >= len(call.Args) {
		return nil
	}
	return an.info.TypeOf(call.Args[i])
}

func litString(an *analyzer, call *ast.CallExpr, i int) string {
	if i >= len(call.Args) {
		return ""
	}
	lit, ok := call.Args[i].(*ast.BasicLit)
	if !ok || lit.Kind != token.STRING {
		return ""
	}
	s, err := strconv.Unquote(lit.Value)
	if err != nil {
		return ""
	}
	return s
}

func litInt(an *analyzer, call *ast.CallExpr, i int) int {
	if i >= len(call.Args) {
		return 0
	}
	tv, ok := an.info.Types[call.Args[i]]
	if !ok || tv.Value == nil {
		return 0
	}
	v, ok := constant.Int64Val(tv.Value)
	if !ok {
		return 0
	}
	return int(v)
}

func (an *analyzer) callee(call *ast.CallExpr) (pkgPath, name string) {
	var id *ast.Ident
	if sel, ok := call.Fun.(*ast.SelectorExpr); ok {
		id = sel.Sel
	} else if ident, ok := call.Fun.(*ast.Ident); ok {
		id = ident
	} else {
		return "", ""
	}
	fn, ok := an.info.Uses[id].(*types.Func)
	if !ok {
		return "", ""
	}
	if fn.Pkg() == nil {
		return "", ""
	}
	return fn.Pkg().Path(), fn.Name()
}

