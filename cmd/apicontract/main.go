type route struct{ Method, Path, Handler string }

func normalizePath(p string) string {
	if p == "/" {
		return "/"
	}
	segs := strings.Split(strings.Trim(p, "/"), "/")
	for i, s := range segs {
		if strings.HasPrefix(s, ":") {
			segs[i] = "{" + strings.TrimPrefix(s, ":") + "}"
		}
		if strings.HasPrefix(s, "*") {
			segs[i] = "{" + strings.TrimPrefix(s, "*") + "}"
		}
	}
	return "/" + strings.Join(segs, "/")
}

// routeTable builds the real router over a throwaway sqlite database and reads the table
// it produced. Parsing router.go instead would be a second description of the routing —
// the duplication that let E159's three routes hide.
func routeTable() ([]route, error) {
	gin.SetMode(gin.TestMode)
	dir, err := os.MkdirTemp("", "rgx-apicontract-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(dir)
	cfg := config.Config{
		Server:   config.Server{Mode: "test"},
		App:      config.App{JWTSecret: "apicontract", JWTExpireHours: 24, DataDir: dir},
		Database: config.Database{Driver: "sqlite", DSN: filepath.Join(dir, "apicontract.db")},
		RAGFlow:  config.RAGFlow{Provider: "mock"},
		Approval: config.Approval{Enabled: true},
	}
	gdb, err := db.Open(cfg.Database)
	if err != nil {
		return nil, err
	}
	if sqlDB, err := gdb.DB(); err == nil {
		defer sqlDB.Close()
	}
	if err := db.Migrate(gdb); err != nil {
		return nil, err
	}
	svc := service.New(repository.NewStore(gdb), ragflow.NewMock(),
		jwt.NewManager(cfg.App.JWTSecret, cfg.App.JWTExpireHours), "apicontract")
	engine := router.New(cfg, handler.New(svc), ratelimit.NewMemory())

	var out []route
	for _, info := range engine.Routes() {
		name := strings.TrimSuffix(info.Handler, "-fm")
		if i := strings.LastIndex(name, "."); i >= 0 {
			name = name[i+1:]
		}
		out = append(out, route{Method: info.Method, Path: info.Path, Handler: name})
	}
	return out, nil
}

// handAnnotated reads `@Router` lines out of every handler file except the generated
// ones, i.e. the contracts a human wrote.
func handAnnotated() (map[string]bool, error) {
	entries, err := os.ReadDir("internal/handler")
	if err != nil {
		return nil, err
	}
	routerLine := regexp.MustCompile(`^//\s*@Router\s+(\S+)\s+\[(\w+)\]`)
	out := map[string]bool{}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || name == "openapi_routes_gen.go" || name == "openapi_contracts_gen.go" {
			continue
		}
		raw, err := os.ReadFile(filepath.Join("internal/handler", name))
		if err != nil {
			return nil, err
		}
		for _, line := range strings.Split(string(raw), "\n") {
			if m := routerLine.FindStringSubmatch(strings.TrimRight(line, "\r")); m != nil {
				out[strings.ToUpper(m[2])+" "+m[1]] = true
			}
		}
	}
	return out, nil
}

type specOp struct{ Method, Path string }

func readSpecOps(path string) ([]specOp, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var spec struct {
		Paths map[string]map[string]json.RawMessage `json:"paths"`
	}
	if err := json.Unmarshal(raw, &spec); err != nil {
		return nil, err
	}
	var ops []specOp
	for p, item := range spec.Paths {
		// `head` is a real method on this router: `r.Static` serves GET and HEAD from one
		// handler, and dropping HEAD from the denominator made a documented operation
		// disappear the day the spec was regenerated (s26 R2).
		for _, m := range []string{"get", "post", "put", "patch", "delete", "head"} {
			if _, ok := item[m]; ok {
				ops = append(ops, specOp{Method: strings.ToUpper(m), Path: p})
			}
		}
	}
	sort.Slice(ops, func(i, j int) bool {
		if ops[i].Path != ops[j].Path {
			return ops[i].Path < ops[j].Path
		}
		return ops[i].Method < ops[j].Method
	})
	return ops, nil
}

