func main() {
	var (
		reportOnly = flag.Bool("report", false, "print readings and refusals, write nothing")
		check      = flag.Bool("check", false, "regenerate in memory and compare with the committed file")
		apply      = flag.Bool("apply", false, "also rewrite the analysed gin.H call sites in place")
		specPath   = flag.String("spec", "internal/docs/swagger.json", "spec whose operations must all gain a contract")
		out        = flag.String("out", outDefault, "generated contract file")
		extOut     = flag.String("extensions", "", "write the machine-readable permission sidecar here (T310-05)")
	)
	flag.Parse()

	specOps, err := readSpecOps(*specPath)
	if err != nil {
		fail("read spec: %v", err)
	}
	// A declared exception may add an operation the committed spec has never carried: the
	// denominator comes from the spec, so without this a route could only be documented by
	// hand-editing the artifact. The exceptions are reviewed code, not derived facts.
	seenOp := map[string]bool{}
	for _, op := range specOps {
		seenOp[op.Method+" "+op.Path] = true
	}
	for key := range staticContracts {
		if seenOp[key] {
			continue
		}
		parts := strings.SplitN(key, " ", 2)
		specOps = append(specOps, specOp{Method: parts[0], Path: parts[1]})
	}
	sort.Slice(specOps, func(i, j int) bool {
		if specOps[i].Path != specOps[j].Path {
			return specOps[i].Path < specOps[j].Path
		}
		return specOps[i].Method < specOps[j].Method
	})
	table, err := routeTable()
	if err != nil {
		fail("route table: %v", err)
	}
	handlers := map[string]string{}
	for _, r := range table {
		handlers[r.Method+" "+normalizePath(r.Path)] = r.Handler
	}
	var missing []string
	for _, op := range specOps {
		if _, declared := staticContracts[op.Method+" "+op.Path]; declared {
			continue
		}
		if handlers[op.Method+" "+op.Path] == "" {
			missing = append(missing, op.Method+" "+op.Path)
		}
	}
	if len(missing) > 0 {
		fail("the spec documents %d operation(s) with no handler in the route table (a generator that skips a route moves the denominator instead of filling it):\n  %s",
			len(missing), strings.Join(missing, "\n  "))
	}

	an, err := newAnalyzer()
	if err != nil {
		fail("load packages: %v", err)
	}

	// Operations that already carry a hand-written contract keep it: batch 1 was written
	// to be read line by line (doc/310 §22.4), and regenerating those would replace
	// reviewed prose with derived prose. The set is read from the annotations themselves,
	// so an endpoint cannot be silently dropped by being listed here.
	hand, err := handAnnotated()
	if err != nil {
		fail("scan existing annotations: %v", err)
	}
	var contracts []contract
	var patches []patch
	var refusals []string
	for _, op := range specOps {
		if hand[op.Method+" "+op.Path] {
			continue
		}
		c, why := an.describe(op.Method, op.Path, handlers[op.Method+" "+op.Path])
		if len(why) > 0 {
			refusals = append(refusals, fmt.Sprintf("%-6s %-60s %s", op.Method, op.Path, strings.Join(why, "；")))
			continue
		}
		contracts = append(contracts, c)
		patches = append(patches, c.Patches...)
	}
	if len(refusals) > 0 {
		fail("%d of %d operations could not be derived — refusing to write a partial contract:\n  %s",
			len(refusals), len(specOps), strings.Join(refusals, "\n  "))
	}

	if *extOut != "" {
		if err := writeExtensions(*extOut, specOps, an); err != nil {
			fail("extensions: %v", err)
		}
	}
	src, err := render(contracts, an)
	if err != nil {
		fail("render: %v", err)
	}
	if *reportOnly {
		report(contracts, patches, an.objOnly, len(specOps))
		return
	}
	if *check {
		old, err := os.ReadFile(*out)
		if err != nil {
			fail("read %s: %v", *out, err)
		}
		if !sameText(old, src) {
			fmt.Fprintf(os.Stderr, "contract file is stale: regenerate with `go run ./cmd/apicontract`\n")
			os.Exit(1)
		}
		fmt.Printf("contract file is fresh: %d operations\n", len(contracts))
		return
	}
	if *apply {
		if err := applyPatches(patches); err != nil {
			fail("apply: %v", err)
		}
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fail("write %s: %v", *out, err)
	}
	report(contracts, patches, an.objOnly, len(specOps))
}

// writeExtensions publishes the half of T310-05 that elides prose: the same
// (method, path) -> (action, resource) table the middleware enforces, keyed by the spec's own
// path spelling. It cannot be emitted as an annotation: swag v2 files an operation-level
// `@x-` under `responses` (operationv3.go:163), which is not a legal OpenAPI response, so the
// key has to be added to the artifacts after generation by
// scripts/release-gate/openapi_extensions.py. Emitting it here keeps the *source* single.
//
// An operation with no rule gets no entry: "no permission" is the middleware's default-deny
// answer for unregistered routes, but the public routes (login, health, the SPA shell) are
// mounted before the RBAC group and legitimately carry none. The gate reads the absence.
func writeExtensions(path string, ops []specOp, an *analyzer) error {
	ext := struct {
		Source     string            `json:"source"`
		Operations map[string]string `json:"operations"`
	}{Source: "internal/router/access.go accessRules", Operations: map[string]string{}}
	for _, op := range ops {
		if p := an.rules[op.Method+" "+op.Path]; p != "" {
			ext.Operations[op.Method+" "+op.Path] = p
		}
	}
	b, err := json.MarshalIndent(ext, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(b, '\n'), 0o644)
}

func fail(format string, args ...interface{}) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}

func sameText(a, b []byte) bool {
	norm := func(in []byte) []byte {
		s := strings.ReplaceAll(string(in), "\r\n", "\n")
		return []byte(strings.TrimRight(s, "\n"))
	}
	return string(norm(a)) == string(norm(b))
}

