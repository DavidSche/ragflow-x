// synthesiseLit registers a literal-keyed payload under `typeName` and queues the rewrite.
// It returns false when the literal cannot be turned into a type (non-literal keys, two
// different shapes for the same name), so the caller can degrade to `object` instead of
// inventing a suffix nobody reviews.
func (an *analyzer) synthesiseLit(unit *funcUnit, lit *ast.CompositeLit, expr ast.Expr, typeName string, res *scanResult) bool {
	fields, ok := an.ginHFields(lit)
	if !ok {
		return false
	}
	if prev, seen := an.resp[typeName]; seen {
		if !sameFields(prev, fields) {
			return false
		}
	} else {
		an.resp[typeName] = fields
		an.pending = append(an.pending, patch{
			File:  an.filename(expr.Pos()),
			Start: an.fset.Position(expr.Pos()).Offset,
			End:   an.fset.Position(expr.End()).Offset,
			Old:   an.source(expr.Pos(), expr.End()),
			New:   ginHRewrite(typeName, lit),
			Why:   "gin.H -> " + typeName + " so the contract and the emitted JSON share one type",
		})
	}
	if !contains(res.payloads, typeName) {
		res.payloads = append(res.payloads, typeName)
	}
	return true
}

// isResponseBody reports whether the literal is `response.Body{…}` — the shared envelope
// that a handful of handlers build by hand instead of calling response.OK.
func (an *analyzer) isResponseBody(lit *ast.CompositeLit) bool {
	t := an.info.TypeOf(lit)
	if t == nil {
		return false
	}
	named, ok := t.(*types.Named)
	if !ok {
		return false
	}
	obj := named.Obj()
	return obj.Pkg() != nil && obj.Pkg().Path() == responsePkg && obj.Name() == "Body"
}

// dataField returns the expression assigned to the Data key of an envelope literal.
func dataField(lit *ast.CompositeLit) ast.Expr {
	for _, elt := range lit.Elts {
		kv, ok := elt.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		if id, ok := kv.Key.(*ast.Ident); ok && id.Name == "Data" {
			return kv.Value
		}
	}
	return nil
}

// nestedPayload names the payload that sits inside a hand-built envelope (`Data: …`).
// First run the literal is a `gin.H` and gets synthesised; after `-apply` it is already a
// named type and only has to be re-declared, otherwise the second run drops it.
func (an *analyzer) nestedPayload(unit *funcUnit, data ast.Expr, typeName string, res *scanResult) string {
	if data == nil {
		return ""
	}
	if isGinH(an, data) {
		dlit, ok := data.(*ast.CompositeLit)
		if !ok || !an.synthesiseLit(unit, dlit, data, typeName, res) {
			return ""
		}
		return typeName
	}
	name := an.renderType(an.info.TypeOf(data))
	if isUntyped(name) {
		return ""
	}
	if _, seen := an.resp[name]; !seen {
		if fields, ok := an.payloadFields(name); ok {
			an.resp[name] = fields
		}
	}
	if !contains(res.payloads, name) {
		res.payloads = append(res.payloads, name)
	}
	return name
}

func (an *analyzer) ginHFields(lit *ast.CompositeLit) ([]field, bool) {
	var out []field
	seen := map[string]bool{}
	for _, elt := range lit.Elts {
		kv, ok := elt.(*ast.KeyValueExpr)
		if !ok {
			return nil, false
		}
		keyLit, ok := kv.Key.(*ast.BasicLit)
		if !ok || keyLit.Kind != token.STRING {
			return nil, false
		}
		key, err := strconv.Unquote(keyLit.Value)
		if err != nil || key == "" || seen[key] {
			return nil, false
		}
		seen[key] = true
		t := an.info.TypeOf(kv.Value)
		if t == nil {
			return nil, false
		}
		typ := an.renderType(t)
		if isUntyped(typ) {
			return nil, false
		}
		out = append(out, field{Name: exportName(key), Type: typ, Key: key})
	}
	if len(out) == 0 {
		return nil, false
	}
	return out, true
}

// exportName turns a JSON key into an exported Go field name. Only the shapes that appear
// in this codebase are special-cased; anything else is CamelCased mechanically.
func exportName(key string) string {
	parts := strings.FieldsFunc(key, func(r rune) bool { return r == '_' || r == '-' || r == '.' })
	var b strings.Builder
	for _, p := range parts {
		lp := strings.ToLower(p)
		switch lp {
		case "id":
			b.WriteString("ID")
		case "ids":
			b.WriteString("IDs")
		case "url":
			b.WriteString("URL")
		case "uri":
			b.WriteString("URI")
		default:
			b.WriteString(upperFirst(p))
		}
	}
	if b.Len() == 0 {
		return "Field"
	}
	if unicode.IsDigit(rune(b.String()[0])) {
		return "F" + b.String()
	}
	return b.String()
}

func ginHRewrite(typeName string, lit *ast.CompositeLit) string {
	var b strings.Builder
	b.WriteString(typeName + "{")
	for i, elt := range lit.Elts {
		kv := elt.(*ast.KeyValueExpr)
		key, _ := strconv.Unquote(kv.Key.(*ast.BasicLit).Value)
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(exportName(key) + ": " + exprText(kv.Value))
	}
	b.WriteString("}")
	return b.String()
}

func exprText(e ast.Expr) string {
	var b strings.Builder
	format.Node(&b, token.NewFileSet(), e)
	return b.String()
}

func (an *analyzer) filename(pos token.Pos) string {
	return an.fset.Position(pos).Filename
}

func (an *analyzer) source(from, to token.Pos) string {
	start := an.fset.Position(from)
	end := an.fset.Position(to)
	raw, err := os.ReadFile(start.Filename)
	if err != nil || end.Offset > len(raw) {
		return ""
	}
	return string(raw[start.Offset:end.Offset])
}

func httperrStatus(an *analyzer, name string, call *ast.CallExpr) (int, int) {
	switch name {
	case "New":
		return litInt(an, call, 0), litInt(an, call, 1)
	case "BadRequest":
		return 400, litInt(an, call, 0)
	case "Unauthorized":
		return 401, 401
	case "Forbidden":
		return 403, 403
	case "NotFound":
		return 404, 404
	case "Conflict":
		return 409, 409
	case "Unprocessable":
		return 422, litInt(an, call, 0)
	case "Internal":
		return 500, 50000
	}
	return 0, 0
}

func callTakesContext(u *funcUnit) bool {
	if u == nil || u.decl.Type == nil || u.decl.Type.Params == nil {
		return false
	}
	for _, f := range u.decl.Type.Params.List {
		star, ok := f.Type.(*ast.StarExpr)
		if !ok {
			continue
		}
		sel, ok := star.X.(*ast.SelectorExpr)
		if ok && sel.Sel.Name == "Context" {
			return true
		}
	}
	return false
}

// ---------------------------------------------------------------- render

func render(cs []contract, an *analyzer) ([]byte, error) {
	var b strings.Builder
	// Compile-time witness: every type an annotation names is referenced here, so a
	// rename breaks the build instead of silently leaving a document behind.
	b.WriteString("// The annotations below name these types; this block makes that a compile-time\n// fact rather than a comment (doc/310 §22.4).\nvar (\n")
	b.WriteString("\t_ = docs.Envelope{}\n")
	for _, c := range cs {
		fmt.Fprintf(&b, "\t_ %s\n", c.Envelope)
		if c.PageType != "" {
			fmt.Fprintf(&b, "\t_ %s\n", c.PageType)
		}
		for _, p := range c.Payloads {
			fmt.Fprintf(&b, "\t_ %s\n", p.Type)
		}
	}
	b.WriteString(")\n\n")

	// goTypes collects only the type strings that reach Go declarations. A package name
	// that appears solely inside an annotation comment (`contract.Token`, `id.UUID`) must
	// not become an import: swag resolves those from the handler package's own imports.
	var goTypes strings.Builder
	seen := map[string]bool{}
	for _, c := range cs {
		for _, r := range c.Requests {
			if seen[r.Type] {
				continue
			}
			seen[r.Type] = true
			fmt.Fprintf(&b, "// %s is the request body of %s %s, derived from the anonymous struct the handler binds.\n", r.Type, c.Method, c.Path)
			fmt.Fprintf(&b, "type %s struct {\n", r.Type)
			for _, f := range r.Fields {
				fmt.Fprintf(&b, "\t%s %s `json:%q`\n", f.Name, f.Type, f.Key)
				goTypes.WriteString(f.Type + " ")
			}
			b.WriteString("}\n\n")
		}
		for _, p := range c.Payloads {
			if seen[p.Type] {
				continue
			}
			seen[p.Type] = true
			fmt.Fprintf(&b, "// %s is the payload of %s %s, derived from the literal map the handler emits.\n", p.Type, c.Method, c.Path)
			fmt.Fprintf(&b, "type %s struct {\n", p.Type)
			for _, f := range p.Fields {
				fmt.Fprintf(&b, "\t%s %s `json:%q`\n", f.Name, f.Type, f.Key)
				goTypes.WriteString(f.Type + " ")
			}
			b.WriteString("}\n\n")
		}
		if c.PageType != "" && !seen[c.PageType] {
			seen[c.PageType] = true
			fmt.Fprintf(&b, "// %s is the paged payload of %s %s: response.Page with a typed item list.\n", c.PageType, c.Method, c.Path)
			fmt.Fprintf(&b, "type %s struct {\n\tresponse.Page\n\tItems []%s `json:\"items\"`\n}\n\n", c.PageType, c.PageItem)
			goTypes.WriteString("response.Page " + c.PageItem + " ")
		}
		if !seen[c.Envelope] {
			seen[c.Envelope] = true
			data := ""
			if c.PageType != "" {
				data = c.PageType
			} else {
				data = envelopeData(c)
			}
			fmt.Fprintf(&b, "// %s is the success envelope of %s %s.\n", c.Envelope, c.Method, c.Path)
			if data == "" {
				b.WriteString("type " + c.Envelope + " struct {\n\tEnvelopeMeta\n}\n\n")
			} else {
				fmt.Fprintf(&b, "type %s struct {\n\tEnvelopeMeta\n\tData %s `json:\"data\"`\n}\n\n", c.Envelope, data)
				goTypes.WriteString(data + " ")
			}
		}
	}
	for _, c := range cs {
		b.WriteString(annotation(c))
	}

	body := b.String()
	candidates := map[string]string{"docs": modulePath + "/internal/docs"}
	// Every package the handler package already imports is a candidate: the type strings
	// above use those names, and go/types will not give me a path from a bare name.
	for _, p := range an.handlerP.Imports() {
		if p.Name() == "" || p.Name() == "_" || p.Name() == "." {
			continue
		}
		candidates[p.Name()] = p.Path()
	}
	for name, path := range an.typePkgs {
		candidates[name] = path
	}
	var names []string
	for name := range candidates {
		if name == "docs" || name == "response" {
			continue
		}
		if strings.Contains(goTypes.String(), name+".") {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	var head strings.Builder
	head.WriteString(generatedBy + "\n\npackage handler\n\nimport (\n")
	fmt.Fprintf(&head, "\t%q\n", candidates["docs"])
	if strings.Contains(goTypes.String(), "response.") {
		fmt.Fprintf(&head, "\t%q\n", responsePkg)
	}
	for _, n := range names {
		fmt.Fprintf(&head, "\t%s %q\n", n, candidates[n])
	}
	head.WriteString(")\n\n")
	src, err := format.Source([]byte(head.String() + body))
	if err != nil {
		return nil, fmt.Errorf("%w\n-----\n%s", err, head.String()+body)
	}
	return src, nil
}

func envelopeData(c contract) string {
	if c.PageType != "" {
		return c.PageType
	}
	for _, s := range c.Success {
		if s.Status >= 300 || s.Kind != "json" {
			continue
		}
		return s.Type
	}
	return ""
}

// produceAlias maps a media type onto the vocabulary `@Produce` accepts. Anything swag
// does not know becomes octet-stream: a wrong alias is a generator error, a downgraded
// alias plus the exact type in the description is a document that still tells the truth.
func produceAlias(media string) string {
	switch media {
	case "application/json":
		return "json"
	case "text/html":
		return "html"
	case "text/plain", "text/csv", "text/event-stream":
		return "plain"
	default:
		return "octet-stream"
	}
}

func annotation(c contract) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// contract%s documents %s %s.\n//\n", c.Envelope, c.Method, c.Path)
	fmt.Fprintf(&b, "// @Summary %s\n", oneLine(c.Summary))
	fmt.Fprintf(&b, "// @Description %s\n", oneLine(c.Description))
	fmt.Fprintf(&b, "// @Tags %s\n", c.Tag)
	fmt.Fprintf(&b, "// @ID %s\n", c.OperationID)
	// No `@x-…` extension for the permission or the error codes: swag v2.0.0-rc6 puts every
	// `@x-` on an operation into **`responses`** (`operationv3.go:163`
	// `o.Responses.Extensions[...]`), not into the operation object, which yields
	// `responses: {"200": …, "x-ragflow-permission": "read:agent"}` — a document that real
	// OpenAPI consumers refuse (`scripts/release-gate/api_doc_gen.py` died on it with
	// `'str' object has no attribute 'get'`). The facts stay where a reader finds them: the
	// permission is named in @Description, the error codes in the @Failure descriptions.
	// Machine-readable extensions wait for T310-05 (doc/304 §7): either upstream fixes the
	// writer, or the extensions are added by a step that rewrites all three artifacts.
	// The scheme is a property of where the route is mounted, not of the RBAC rule: an
	// endpoint that only requires a valid login (`GET /api/v1/agents/{id}`) still needs
	// `BearerAuth`, and a public one must carry none.
	for _, scheme := range c.Security {
		fmt.Fprintf(&b, "// @Security %s\n", scheme)
	}
	for _, p := range c.Params {
		fmt.Fprintf(&b, "// @Param %s %s %s %t %q\n", p.Name, p.In, p.Type, p.Required, p.Desc)
	}
	if c.Request != "" {
		// Without @Accept swag labels an inline `object` body text/plain, which no client
		// can bind and no gate can read (a real $ref only survives by accident).
		fmt.Fprintf(&b, "// @Accept json\n")
		fmt.Fprintf(&b, "// @Param body body %s true \"请求体（%s）\"\n", c.Request, c.Request)
	} else if isWrite(c.Method) {
		fmt.Fprintf(&b, "// @Accept json\n")
		fmt.Fprintf(&b, "// @Param body body object false %q\n", "本接口不接受请求体")
	}
	for _, s := range c.Success {
		switch s.Kind {
		case "json":
			fmt.Fprintf(&b, "// @Success %d {object} %s\n", s.Status, c.Envelope)
		case "media":
			// swag only accepts its own aliases (json/plain/octet-stream/…), not MIME strings, so
			// the exact media type goes into the success description where a client reads it
			// instead of being silently dropped.
			fmt.Fprintf(&b, "// @Produce %s\n", produceAlias(s.Media))
			fmt.Fprintf(&b, "// @Success %d {string} string \"原始字节；媒体类型即载荷：%s\"\n", s.Status, s.Media)
		case "nobody":
			// No body at all is a real answer (204/205 and `c.Status(…)`-only handlers);
			// saying so is the only honest option, and the gate accepts exactly that.
			fmt.Fprintf(&b, "// @Success %d \"无响应体\"\n", s.Status)
		case "redirect":
			fmt.Fprintf(&b, "// @Success %d {string} string \"浏览器跟随 Location\"\n", s.Status)
			fmt.Fprintf(&b, "// @Header %d {string} Location \"跳转目标\"\n", s.Status)
		}
	}
	if len(c.Errors) > 0 {
		byStatus := map[int][]string{}
		for _, e := range c.Errors {
			byStatus[e.Status] = append(byStatus[e.Status], strconv.Itoa(e.Code))
		}
		statuses := make([]int, 0, len(byStatus))
		for st := range byStatus {
			statuses = append(statuses, st)
		}
		sort.Ints(statuses)
		for _, st := range statuses {
			fmt.Fprintf(&b, "// @Failure %d {object} docs.Envelope \"错误码 %s\"\n", st, strings.Join(byStatus[st], " / "))
		}
	}
	fmt.Fprintf(&b, "// @Router %s [%s]\n", c.Path, strings.ToLower(c.Method))
	fmt.Fprintf(&b, "func contract%s() {}\n\n", c.Envelope)
	return b.String()
}

func oneLine(s string) string {
	s = strings.ReplaceAll(s, "\r", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "\t", " ")
	return strings.Join(strings.Fields(s), " ")
}

// ---------------------------------------------------------------- apply

func applyPatches(ps []patch) error {
	byFile := map[string][]patch{}
	for _, p := range ps {
		byFile[p.File] = append(byFile[p.File], p)
	}
	for file, list := range byFile {
		sort.Slice(list, func(i, j int) bool { return list[i].Start > list[j].Start })
		raw, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		text := string(raw)
		for _, p := range list {
			if p.Start < 0 || p.End > len(text) {
				return fmt.Errorf("%s: patch range %d..%d outside the file", file, p.Start, p.End)
			}
			if text[p.Start:p.End] != p.Old {
				return fmt.Errorf("%s: patch does not match the bytes at %d (%q != %q)", file, p.Start, text[p.Start:p.End], p.Old)
			}
			text = text[:p.Start] + p.New + text[p.End:]
		}
		// gofmt the whole file after splicing: replacing a multi-line gin.H{...} with a
		// one-line composite literal leaves the sibling keys aligned for the old width, and
		// `s02.gofmt-touched` reads that as "the generator writes unformatted code" (it does,
		// and only gofmt knows where the tabs go). Refuse instead of writing bytes gofmt
		// would rewrite: a file that no longer parses means a patch landed in the wrong place.
		formatted, err := format.Source([]byte(text))
		if err != nil {
			return fmt.Errorf("%s: patched file does not parse (%v) — the patch landed in the wrong place", file, err)
		}
		text = string(formatted)
		tmp := file + ".tmp"
		if err := os.WriteFile(tmp, []byte(text), 0o644); err != nil {
			return err
		}
		if err := os.Rename(tmp, file); err != nil {
			return err
		}
	}
	return nil
}

// report prints readings, not a verdict: every number here is something a later reader can
// re-measure, and the spec total is passed in so "589 generated" cannot be mistaken for
// "589 operations documented" (28 operations are hand-annotated and kept verbatim).
func report(cs []contract, ps []patch, objOnly, specTotal int) {
	withBody, withPerm, withErr, pages, media, redirects := 0, 0, 0, 0, 0, 0
	for _, c := range cs {
		if c.Request != "" {
			withBody++
		}
		if c.Permission != "" {
			withPerm++
		}
		if len(c.Errors) > 0 {
			withErr++
		}
		if c.PageType != "" {
			pages++
		}
		for _, s := range c.Success {
			switch s.Kind {
			case "media":
				media++
			case "redirect":
				redirects++
			}
		}
	}
	fmt.Printf("operations:            %d generated + %d hand-annotated = %d in the spec\n", len(cs), specTotal-len(cs), specTotal)
	fmt.Printf("with request body:     %d\n", withBody)
	fmt.Printf("with permission:       %d\n", withPerm)
	fmt.Printf("with error codes:      %d\n", withErr)
	fmt.Printf("paged envelopes:       %d\n", pages)
	fmt.Printf("non-JSON payloads:     %d (media %d, redirects %d)\n", media+redirects, media, redirects)
	fmt.Printf("request bodies as bare object: %d\n", objOnly)
	fmt.Printf("stray path params dropped: %d (a `c.Param` name the route path does not declare)\n", strayPathParams)
	fmt.Printf("handler rewrites pending: %d\n", len(ps))
}
