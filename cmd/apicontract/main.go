// Command apicontract derives the OpenAPI contract of every documented route from the
// code that actually serves it (doc/310 §22 T310-01, batches 2..8).
//
// Why a generator and not 589 hand-written blocks
// ----------------------------------------------
// Batch 1 (28 endpoints: auth/users/roles/tenants) was written by hand because four
// domains are few enough to review line by line. The remaining 589 are not: at that size
// a human writes the first 60 carefully and copies the rest, and a copied `@Success` that
// names the wrong type is worse than no annotation at all — it is a published contract
// that is false (doc/310 §8.2.1, doc/304 §4 E167). Every fact a contract needs is already
// in the tree, in machine-readable form:
//
//	path/method   ← the route table the router builds (not a second list: E138)
//	handler       ← gin's RouteInfo.Handler
//	request body  ← the type the handler passes to ShouldBindJSON (and friends)
//	path params   ← c.Param("name")
//	query params  ← c.Query / c.DefaultQuery / c.GetQuery / c.QueryArray
//	success       ← response.OK / OKPage / Created / Accepted / At / c.JSON / c.Data …
//	error codes   ← httperr.New / httperr.BadRequest … at the return points (P-310-13)
//	permission    ← accessRules — the same table the middleware enforces (T310-05)
//
// So this tool reads those facts with go/types and writes them out. What it cannot derive
// it refuses to invent: every gap becomes a refusal line and a non-zero exit, because
// "generated" must not become a synonym for "plausible".
//
// `gin.H{...}` payloads
// --------------------
// ~120 handlers emit an untyped map. A map has no schema, so the contract would name a
// type the client cannot use. For a literal-keyed `gin.H` the shape *is* derivable, so the
// tool synthesises a named struct and (`-apply`) rewrites that one expression to emit it.
// The JSON wire shape is unchanged (tags carry the original keys); what changes is that the
// compiler and the document now describe the same type (P-310-10).
//
// Usage:
//
//	go run ./cmd/apicontract -report           # readings + refusals, writes nothing
//	go run ./cmd/apicontract                   # write the contract file
//	go run ./cmd/apicontract -apply            # contract file + rewrite gin.H call sites
//	go run ./cmd/apicontract -check            # regenerate and compare with the committed file
