type analyzer struct {
	fset     *token.FileSet
	handlerP *types.Package
	serviceP *types.Package
	info     *types.Info
	svcInfo  *types.Info
	funcs    map[string]*funcUnit
	svcFuncs map[string]*funcUnit
	methods  map[string]*funcUnit // *Handler methods: `h.decision(c, …)` carries body+answer
	rules    map[string]string
	decls    map[string]bool
	pending  []patch            // rewrites discovered while scanning the current operation
	typePkgs map[string]string  // package name -> import path, for the generated file
	resp     map[string][]field // synthesised response type -> its fields
	req      map[string][]field // synthesised request type -> its fields
	objOnly  int                // request bodies that could only be documented as `object`
	usedIDs  map[string]bool    // operationIds already allocated (must be unique: R1)
	origin   map[string]string  // type name -> file that declares it
}

type funcUnit struct {
	decl *ast.FuncDecl
	body *ast.BlockStmt
	doc  string
}

