	handlerPkg  = modulePath + "/internal/handler"
	servicePkg  = modulePath + "/internal/service"
	responsePkg = modulePath + "/internal/pkg/response"
	httperrPkg  = modulePath + "/internal/pkg/httperr"
	outDefault  = "internal/handler/openapi_contracts_gen.go"
	generatedBy = "// Code generated by `go run ./cmd/apicontract`; DO NOT EDIT."
