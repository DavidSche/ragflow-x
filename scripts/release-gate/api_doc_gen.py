# `head` is a real operation on this router: `r.Static` serves GET and HEAD from one handler,
# and the spec declares both. Leaving it out of this list made the rendered document describe
# 616 of the 617 operations the spec carries — and the gate could not see it, because its own
# denominator used the same five-method list (a shared blindness, not a check).
METHOD_ORDER = ["get", "post", "put", "patch", "delete", "head"]
METHOD_LABEL = {"get": "GET", "post": "POST", "put": "PUT", "patch": "PATCH",
                "delete": "DELETE", "head": "HEAD"}
PLACEHOLDER_SUMMARIES = {"Auto-generated API route", ""}
HTML_ESCAPES = [("&", "&amp;"), ("<", "&lt;"), (">", "&gt;"), ('"', "&quot;")]


def esc(text):
    out = str(text)
    for old, new in HTML_ESCAPES:
        out = out.replace(old, new)
    return out


def type_of(schema):
    """A one-line, human-readable type. Never invents structure it cannot see."""
    if not isinstance(schema, dict) or not schema:
        return "—"
    ref = schema.get("$ref")
    if ref:
        return "`%s`" % ref.rsplit("/", 1)[-1]
    if "enum" in schema and isinstance(schema["enum"], list):
        values = schema["enum"]
        shown = ", ".join(str(v) for v in values[:6])
        more = "" if len(values) <= 6 else " … (%d 个值)" % len(values)
        return "enum(%s%s)" % (shown, more)
    kind = schema.get("type")
    if kind == "array":
        return "array<%s>" % type_of(schema.get("items", {})).strip("`")
    if kind == "object":
        props = schema.get("properties") or {}
        return "object(%d 字段)" % len(props) if props else "object"
    if kind:
        fmt = schema.get("format")
        return "%s(%s)" % (kind, fmt) if fmt else kind
    return "—"


def parameters_of(op):
    rows = []
    for param in op.get("parameters") or []:
        schema = param.get("schema") or {}
        rows.append({
            "name": param.get("name", "?"),
            "in": param.get("in", "?"),
            "type": type_of(schema),
            "required": "是" if param.get("required") else "否",
            "desc": (param.get("description") or "").strip(),
        })
    return rows


def responses_of(op):
    rows = []
    for code in sorted((op.get("responses") or {}).keys()):
        resp = op["responses"][code]
        content = resp.get("content") or {}
        schemas = []
        for media in sorted(content.keys()):
            schemas.append("%s → %s" % (media, type_of(content[media].get("schema"))))
        rows.append({
            "code": str(code),
            "desc": (resp.get("description") or "").strip(),
            "schema": "; ".join(schemas) or "—",
        })
    return rows


def bodies_of(op):
    rows = []
    for media, spec in sorted(((op.get("requestBody") or {}).get("content") or {}).items()):
        rows.append({
            "media": media,
            "schema": type_of(spec.get("schema")),
            "required": "是" if (op.get("requestBody") or {}).get("required") else "否",
        })
    return rows


def group_key(path):
    """Group by the first segment after /api/v1/ so the TOC reads like the product."""
    parts = [p for p in path.split("/") if p]
    if len(parts) >= 3 and parts[0] == "api" and parts[1] == "v1":
        return parts[2]
    if len(parts) >= 2:
        return parts[0] + "/" + parts[1]
    return path.strip("/") or "root"


def walk(spec):
    ops = []
    for path in sorted(spec.get("paths") or {}):
        for method in METHOD_ORDER:
            op = (spec["paths"][path] or {}).get(method)
            if not isinstance(op, dict):
                continue
            summary = (op.get("summary") or "").strip()
            security = op.get("security")
            ops.append({
                "method": METHOD_LABEL[method],
                "path": path,
                "group": group_key(path),
                "operationId": op.get("operationId") or "—",
                "summary": summary,
                "placeholder": summary in PLACEHOLDER_SUMMARIES,
                "description": (op.get("description") or "").strip(),
                "auth": "BearerAuth" if security else "公开（无 security 声明）",
                "perm": op.get("x-ragflow-permission") or "",
                "codes": op.get("x-error-codes") or [],
                "params": parameters_of(op),
                "bodies": bodies_of(op),
                "responses": responses_of(op),
            })
    return ops


def maturity(spec, ops):
    """The numbers the document leads with. Read from the spec, never hard-coded."""
    schemes = sorted((spec.get("components") or {}).get("securitySchemes") or {})
    schemas = sorted((spec.get("components") or {}).get("schemas") or {})
    return OrderedDict([
        ("operations", len(ops)),
        ("paths", len({o["path"] for o in ops})),
        ("groups", len({o["group"] for o in ops})),
        ("summary_unannotated", sum(1 for o in ops if o["placeholder"])),
        ("with_description", sum(1 for o in ops if o["description"])),
        ("with_request_body", sum(1 for o in ops if o["bodies"])),
        ("with_parameters", sum(1 for o in ops if o["params"])),
        ("with_permission", sum(1 for o in ops if o["perm"])),
        ("with_error_codes", sum(1 for o in ops if o["codes"])),
        ("schemas", len(schemas)),
        ("schema_names", schemas),
        ("security_schemes", schemes),
    ])


def grouped(ops):
    out = OrderedDict()
    for op in ops:
        out.setdefault(op["group"], []).append(op)
    return out


