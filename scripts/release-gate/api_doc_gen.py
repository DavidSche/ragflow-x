def render_md(spec, ops, mat, source_name):
    info = spec.get("info") or {}
    spec_version = spec.get("openapi") or "?"
    api_version = info.get("version") or "?"
    lines = []
    w = lines.append

    w("# RAGFlow-X 接口参考（%s）" % esc("OpenAPI " + spec_version))
    w("")
    w("> **本文件是生成物，不要手改。** 源 = `%s`（`info.version %s`，%d 条路径 / %d 个操作），"
      % (source_name, api_version, mat["paths"], mat["operations"]))
    w("> 生成命令：`bash scripts/release-gate/api-doc.sh gen`；")
    w("> 门禁 `s28.api-doc` 会重新生成并**逐字节**比较，手改必红。")
    w("")
    w("## 这份文档能说什么、不能说什么")
    w("")
    w("它由 OpenAPI 描述符渲染而来，所以它只能写下描述符里真的有的东西。"
      "下面的数字是每次生成时从描述符里**数出来**的——它们变，文档就变，门禁就红。")
    w("")
    w("| 项 | 数量 | 含义 |")
    w("| --- | --- | --- |")
    w("| 路径 / 操作 | %d / %d | 路由清单本身是完整的 |" % (mat["paths"], mat["operations"]))
    w("| 操作标题仍是占位符 | %d / %d | `Auto-generated API route` = handler 上没有 `@Summary` 注解 |"
      % (mat["summary_unannotated"], mat["operations"]))
    w("| 有 `@Description` | %d / %d | 业务语义、前置条件、副作用 |" % (mat["with_description"], mat["operations"]))
    w("| 有请求体 | %d / %d | 从 handler 的 `ShouldBindJSON` 类型派生 |"
      % (mat["with_request_body"], mat["operations"]))
    w("| 有参数 | %d / %d | 路径/查询参数的名字、位置、类型、是否必填 |"
      % (mat["with_parameters"], mat["operations"]))
    w("| 写了所需权限 | %d / %d | `x-ragflow-permission` = 服务端 RBAC 表的 `(action, resource)` |"
      % (mat["with_permission"], mat["operations"]))
    w("| 写了业务错误码 | %d / %d | `x-error-codes` = 该操作失败响应里点名的 `httperr` 码 |"
      % (mat["with_error_codes"], mat["operations"]))
    w("| 声明的 schema | %d（%s） | 信封与业务对象，名字对得上 handler 里的 Go 类型 |"
      % (mat["schemas"], "、".join(mat["schema_names"]) or "无"))
    w("| 鉴权 scheme | %s | 所有受保护端点都是 Bearer JWT |"
      % ("、".join(mat["security_schemes"]) or "无"))
    w("")
    if mat["summary_unannotated"] == mat["operations"] or mat["with_request_body"] == 0:
        w("> **当前状态：这是路由契约，不是业务接口手册。** 路径、方法、参数位置与鉴权是准确的；"
          "请求体字段、业务语义和错误码**尚未注解**。发给外部集成方之前，至少先给对外的端点补上"
          " `@Summary` / `@Description` / `@Param … body` / `@Success`，再重新生成——"
          "否则这份文件会让收件人以为“接口就这么简单”。")
        w("")
    w("## 约定")
    w("")
    w("- Base URL：任一部署实例，形如 `https://<your-host>`（本机开发常见 `http://localhost:19193`）；所有业务路径都以 `/api/v1` 开头。")
    w("- 鉴权：`Authorization: Bearer <JWT>`。JWT 由 `POST /api/v1/auth/login` 换取"
      "（body：`{\"username\": \"…\", \"password\": \"…\"}`，响应 `data.token`）。")
    w("- 响应信封：`{\"code\": 0, \"message\": \"ok\", \"data\": {…}, \"trace_id\": \"…\"}`；"
      "`code != 0` 时 `message` 可读，`trace_id` 用于对日志。")
    w("- 权限：每个受保护端点除了 Bearer JWT，服务端还有一层 RBAC `(action, resource)` 判断。"
      "本文件把该值写进每个端点的 `x-ragflow-permission`（`read`/`manage`/`execute` + 资源名），"
      "`无（公开路由）` 表示这条路走在 RBAC 组之前；角色→权限的授予关系见 "
      "`doc/user/zh-CN/permission-matrix.md`。")
    w("- 业务错误码：`x-error-codes` 列出该端点失败时可能返回的业务码（`code` 字段）。"
      "空数组表示这个端点只在 HTTP 层失败（401/403/404 等），没有业务码；"
      "码到中文句子的映射见 `web/src/lib/errors.ts`。")
    w("")
    w("## 目录")
    w("")
    groups = grouped(ops)
    for name in groups:
        w("- **%s**（%d）" % (esc(name), len(groups[name])))
    w("")
    for name, items in groups.items():
        w("## %s（%d 个操作）" % (esc(name), len(items)))
        w("")
        for op in items:
            w("### %s `%s`" % (op["method"], esc(op["path"])))
            w("")
            title = "（未注解，见文首说明）" if op["placeholder"] else esc(op["summary"])
            w("- 说明：%s" % title)
            w("- 鉴权：%s" % esc(op["auth"]))
            w("- 所需权限：%s" % ("`%s`" % op["perm"] if op["perm"] else "无（公开路由）"))
            if op["codes"]:
                w("- 业务错误码：%s" % "、".join("`%s`" % c for c in op["codes"]))
            else:
                w("- 业务错误码：无（只在 HTTP 层失败）")
            w("- operationId：`%s`" % op["operationId"])
            if op["description"]:
                w("- 描述：%s" % esc(op["description"]))
            w("")
            if op["params"]:
                w("| 参数 | 位置 | 类型 | 必填 | 说明 |")
                w("| --- | --- | --- | --- | --- |")
                for p in op["params"]:
                    w("| `%s` | %s | %s | %s | %s |"
                      % (p["name"], p["in"], p["type"].replace("|", "\\|"), p["required"],
                         esc(p["desc"]) or "—"))
                w("")
            if op["bodies"]:
                w("| 请求体类型 | Schema | 必填 |")
                w("| --- | --- | --- |")
                for b in op["bodies"]:
                    w("| %s | %s | %s |" % (b["media"], b["schema"], b["required"]))
                w("")
            if op["responses"]:
                w("| 状态码 | 说明 | 响应 schema |")
                w("| --- | --- | --- |")
                for r in op["responses"]:
                    w("| %s | %s | %s |" % (r["code"], esc(r["desc"]) or "—", r["schema"]))
                w("")
    w("---")
    w("")
    w("生成器：`scripts/release-gate/api_doc_gen.py`；门禁：`s28.api-doc`（`--selftest` 证明它会红）。")
    w("")
    return "\n".join(lines)


