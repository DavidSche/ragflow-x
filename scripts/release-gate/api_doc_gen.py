#!/usr/bin/env python3
"""api_doc_gen.py — render the committed OpenAPI spec into a hand-out-able reference.

Input : internal/docs/swagger.json   (tracked, freshness-checked by s25.openapi-freshness)
Output: doc/specification/api/api-reference.md
        doc/specification/api/api-reference.html

Why this file exists (doc/304 §4 E161): "把 spec 发给客户" is not a thing you can do —
a 674 KB JSON with `$ref`s is a machine artifact. What a customer needs is a document
that says, per endpoint, what to call, what to pass and what comes back. That is a
*rendering*, and a rendering that is produced once by hand rots the first time a route
changes. So it is produced from the same bytes the binary serves, and s28.api-doc
regenerates it and compares byte-for-byte.

What this renderer refuses to fake
---------------------------------
The spec is generated by `swag` from the `@Router`/`@Param`/`@Success` annotations in
internal/handler/openapi_routes_gen.go. Today those annotations carry the route and its
parameters but no summary, no request/response bodies and one shared envelope schema —
so 616/616 operations are titled "Auto-generated API route". Rendering that as a
professional interface manual would be a lie told in good typography. Instead the
document leads with a **computed** maturity box: the counts are read from the spec on
every generation, so the day someone annotates a handler, the numbers move and the gate
goes red until the document is regenerated. The document says what it can prove:
method, path, path/query parameter names and types, required-ness, and the auth scheme.

Determinism (the check compares bytes)
-------------------------------------
No timestamps, no locale-dependent sorting (explicit `sorted(...)`), LF newlines,
`ensure_ascii=False` nowhere (this file writes text directly), stable group order by
first path segment. A single byte of drift must mean the spec or this renderer changed,
never "it ran on another day".

Usage: python api_doc_gen.py <spec.json> <out-dir>
"""

