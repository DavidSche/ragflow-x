#!/usr/bin/env node
// Generates the TypeScript view of the published OpenAPI document
// (doc/develop/310 §22 T310-03, doc/specification/14).
//
//   node scripts/api-types.mjs          write src/types/openapi.d.ts
//   node scripts/api-types.mjs --check  fail if the committed file is stale
//
// The contract is generated, never hand-written: the artifact is what makes a
// backend field rename break `tsc -b` in the console instead of at runtime.
// `--check` runs the same transform and compares bytes, so a forgotten
// regeneration is a red gate rather than a stale type that still compiles.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const specPath = resolve(here, "../../internal/docs/swagger.json");
const outPath = resolve(here, "../src/types/openapi.d.ts");
const check = process.argv.includes("--check");

const ast = await openapiTS(new URL(`file://${specPath.replaceAll("\\", "/")}`), {
  // Keep the Go-qualified schema keys. Renaming them here would invent a
  // vocabulary the server does not have, and the alias layer in
  // src/types/api.ts is the one place allowed to give them readable names.
  alphabetize: true,
  exportType: true,
});

const header = `/**
 * Generated by web/scripts/api-types.mjs from internal/docs/swagger.json.
 * Do not edit: run \`npm run gen:types\` instead (doc/310 T310-03).
 */
`;
const next = header + astToString(ast);

if (!check) {
  await writeFile(outPath, next, "utf8");
  console.log(`api-types: wrote ${outPath} (${next.length.toLocaleString()} bytes)`);
  process.exit(0);
}

let current = "";
try {
  current = await readFile(outPath, "utf8");
} catch {
  console.error(`api-types: ${outPath} is missing — run \`npm run gen:types\``);
  process.exit(1);
}
// git checkout on this box may hand back CRLF; the bytes, not the line endings,
// are the contract.
const norm = (s) => s.replaceAll("\r\n", "\n");
if (norm(current) !== norm(next)) {
  console.error(`api-types: ${outPath} is stale — run \`npm run gen:types\` and commit the result`);
  process.exit(1);
}
console.log(`api-types: up to date (${norm(next).length.toLocaleString()} bytes)`);
